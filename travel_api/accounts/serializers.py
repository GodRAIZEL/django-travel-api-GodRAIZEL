"""Serializers for registration, login, profile management and passwords."""
from django.contrib.auth import authenticate, get_user_model
from django.contrib.auth.password_validation import validate_password
from rest_framework import serializers

User = get_user_model()


class UserSerializer(serializers.ModelSerializer):
    """General-purpose read/update serializer for the authenticated user's own profile."""
    full_name = serializers.ReadOnlyField()

    class Meta:
        model = User
        fields = [
            'id', 'username', 'email', 'first_name', 'last_name', 'full_name',
            'phone', 'date_of_birth', 'bio', 'profile_picture',
            'travel_preferences', 'created_at',
        ]
        read_only_fields = ['id', 'username', 'created_at']

    def validate_travel_preferences(self, value):
        if value and not isinstance(value, dict):
            raise serializers.ValidationError('travel_preferences must be a JSON object.')
        return value


class UserRegistrationSerializer(serializers.ModelSerializer):
    """
    Handles account creation. Passwords are write-only and validated with
    Django's built-in password validators; password confirmation is
    checked with object-level validation.
    """
    password = serializers.CharField(
        write_only=True, style={'input_type': 'password'},
        help_text='At least 8 characters; must pass Django\'s standard password validators.',
    )
    password_confirm = serializers.CharField(
        write_only=True, style={'input_type': 'password'},
        help_text='Repeat the password exactly - must match the password field.',
    )

    class Meta:
        model = User
        fields = ['username', 'email', 'password', 'password_confirm', 'first_name', 'last_name']

    def validate_email(self, value):
        if User.objects.filter(email__iexact=value).exists():
            raise serializers.ValidationError('A user with this email already exists.')
        return value

    def validate_password(self, value):
        validate_password(value)
        return value

    def validate(self, attrs):
        if attrs['password'] != attrs['password_confirm']:
            raise serializers.ValidationError({'password_confirm': "Passwords don't match."})
        return attrs

    def create(self, validated_data):
        validated_data.pop('password_confirm')
        password = validated_data.pop('password')
        user = User(**validated_data)
        user.set_password(password)
        user.save()
        return user


class LoginSerializer(serializers.Serializer):
    """Validates username/password credentials for the login endpoint."""
    username = serializers.CharField()
    password = serializers.CharField(write_only=True, style={'input_type': 'password'})

    def validate(self, attrs):
        user = authenticate(username=attrs['username'], password=attrs['password'])
        if not user:
            raise serializers.ValidationError('Invalid credentials.')
        if not user.is_active:
            raise serializers.ValidationError('This account has been deactivated.')
        attrs['user'] = user
        return attrs


class PasswordChangeSerializer(serializers.Serializer):
    """Validates old + new password for an authenticated password change."""
    old_password = serializers.CharField(write_only=True)
    new_password = serializers.CharField(write_only=True)
    new_password_confirm = serializers.CharField(write_only=True)

    def validate_old_password(self, value):
        user = self.context['request'].user
        if not user.check_password(value):
            raise serializers.ValidationError('Old password is incorrect.')
        return value

    def validate_new_password(self, value):
        validate_password(value)
        return value

    def validate(self, attrs):
        if attrs['new_password'] != attrs['new_password_confirm']:
            raise serializers.ValidationError({'new_password_confirm': "Passwords don't match."})
        return attrs

    def save(self, **kwargs):
        user = self.context['request'].user
        user.set_password(self.validated_data['new_password'])
        user.save()
        return user


class PasswordResetRequestSerializer(serializers.Serializer):
    """Accepts an email and (silently) issues a reset token if it matches an account."""
    email = serializers.EmailField()


class PasswordResetConfirmSerializer(serializers.Serializer):
    """Confirms a password reset using a uidb64/token pair, as generated by Django's
    default token generator."""
    uid = serializers.CharField()
    token = serializers.CharField()
    new_password = serializers.CharField(write_only=True)

    def validate_new_password(self, value):
        validate_password(value)
        return value
